using System;
using System.Runtime.InteropServices;
using ComputeSharp.D2D1;

public static partial class Probe
{
    [DllImport("d3dcompiler_47", ExactSpelling = true)]
    private static extern unsafe int D3DDisassemble(void* data, nuint size, uint flags, byte* comments, out IntPtr disassembly);

    private static unsafe void CheckCompiledBytecode(ReadOnlySpan<byte> bytecode)
    {
        Require(bytecode.Length > 32 && bytecode[..4].SequenceEqual("DXBC"u8), "HLSL source bytes are not compiled shader bytecode");
        fixed (byte* pointer = bytecode)
        {
            int result = D3DDisassemble(pointer, (nuint)bytecode.Length, 0, null, out IntPtr disassembly);
            try
            {
                Require(result >= 0 && disassembly != IntPtr.Zero, "real compiler rejected generated bytecode during disassembly");
            }
            finally
            {
                if (disassembly != IntPtr.Zero) Release(disassembly);
            }
        }
    }

    [D2DPixelShaderSource("""
        #define D2D_INPUT_COUNT 1
        #define D2D_INPUT0_SIMPLE
        #include "d2d1effecthelpers.hlsli"
        D2D_PS_ENTRY(Execute)
        {
            float4 color = D2DGetInput(0);
            return float4(color.brg * 0.5, 0.25);
        }
        """)]
    [ComputeSharp.D2D1.D2DShaderProfile(ComputeSharp.D2D1.D2D1ShaderProfile.PixelShader50)]
    [ComputeSharp.D2D1.D2DCompileOptions(ComputeSharp.D2D1.D2D1CompileOptions.OptimizationLevel0)]
    private static partial ReadOnlySpan<byte> GetDifferentStandaloneBytecode();
}
